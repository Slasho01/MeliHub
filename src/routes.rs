use crate::controller::{admin_controller as adm, api_key_controller as keys, auth_controller as auth, auditoria_controller as audit, cupon_controller as cupon, equipo_controller as equipo, facturacion_controller as fact, falabella_controller as fala, health, ml_controller as ml, preguntas_controller as preg, producto_controller as prod, pub_controller as pubc, saas_controller as saas, suscripcion_controller as subs, venta_controller as ventas};
use actix_web::web::{self, delete, get, post, put, resource as r};

pub fn configure(cfg: &mut web::ServiceConfig) {
    cfg.service(
        web::scope("/api")
            .service(r("/health").route(get().to(health)))
            // Auth del hub
            .service(r("/auth/registro").route(post().to(auth::registrar)))
            .service(r("/auth/login").route(post().to(auth::login)))
            .service(r("/auth/login/2fa").route(post().to(auth::login_2fa)))
            .service(r("/auth/forgot").route(post().to(auth::forgot)))
            .service(r("/auth/reset").route(post().to(auth::reset)))
            .service(r("/auth/me").route(get().to(auth::me)))
            .service(r("/auth/logout-all").route(post().to(auth::logout_all)))
            .service(r("/auth/perfil").route(put().to(auth::actualizar_perfil)))
            .service(r("/auth/password").route(put().to(auth::cambiar_password)))
            .service(r("/auth/2fa/setup").route(post().to(auth::twofa_setup)))
            .service(r("/auth/2fa/enable").route(post().to(auth::twofa_enable)))
            .service(r("/auth/2fa/disable").route(post().to(auth::twofa_disable)))
            // Equipo (miembros de la organización)
            .service(r("/equipo/aceptar").route(post().to(equipo::aceptar))) // público (invitado)
            .service(r("/equipo").route(get().to(equipo::listar)).route(post().to(equipo::invitar)))
            .service(r("/equipo/{id}").route(put().to(equipo::cambiar_rol)).route(delete().to(equipo::eliminar)))
            .service(r("/equipo/{id}/reinvitar").route(post().to(equipo::reinvitar)))
            // Mercado Libre: OAuth y cuentas
            .service(r("/ml/conectar").route(post().to(ml::conectar)))
            .service(r("/ml/callback").route(get().to(ml::callback)))
            .service(r("/ml/webhook").route(post().to(ml::webhook)))
            .service(r("/ml/cuentas").route(get().to(ml::listar_cuentas)))
            .service(r("/ml/cuentas/{id}").route(delete().to(ml::desconectar)))
            .service(r("/ml/cuentas/{id}/sincronizar").route(post().to(ml::sincronizar)))
            // Preguntas de compradores (centralizadas de todas las cuentas)
            .service(r("/ml/preguntas").route(get().to(preg::listar)))
            .service(r("/ml/preguntas/responder").route(post().to(preg::responder)))
            // Falabella Seller Center (cuentas)
            .service(r("/falabella/cuentas").route(get().to(fala::listar)).route(post().to(fala::conectar)))
            .service(r("/falabella/cuentas/{id}").route(delete().to(fala::desconectar)))
            .service(r("/falabella/marcas").route(get().to(fala::marcas)))
            .service(r("/falabella/ordenes").route(get().to(fala::ordenes)))
            .service(r("/falabella/ordenes/listo").route(post().to(fala::orden_listo)))
            .service(r("/falabella/ordenes/documento").route(get().to(fala::orden_documento)))
            .service(r("/falabella/categorias").route(get().to(fala::categorias)))
            .service(r("/falabella/categorias/atributos").route(get().to(fala::atributos)))
            .service(r("/falabella/publicar").route(post().to(fala::publicar)))
            .service(r("/falabella/republicar").route(post().to(fala::republicar)))
            .service(r("/falabella/imagenes").route(post().to(fala::subir_imagenes)))
            .service(r("/falabella/estado").route(post().to(fala::cambiar_estado)))
            .service(r("/falabella/webhook/registrar").route(post().to(fala::registrar_webhook)))
            .service(r("/falabella/webhook/{id}").route(post().to(fala::webhook)))
            .service(r("/falabella/publicaciones").route(get().to(fala::publicaciones)))
            .service(r("/falabella/productos").route(get().to(fala::productos_fala)))
            .service(r("/falabella/feeds").route(get().to(fala::feeds)))
            .service(r("/falabella/feed").route(get().to(fala::feed_estado)))
            // Catálogo unificado + gestor de inventario
            .service(r("/productos").route(get().to(prod::listar)))
            .service(r("/productos/inventario-masivo").route(post().to(prod::inventario_masivo)))
            .service(r("/productos/alertas").route(get().to(prod::alertas)))
            .service(r("/productos/{id}/inventario").route(put().to(prod::set_inventario)))
            .service(r("/productos/{id}/ml/estado").route(post().to(prod::set_estado_ml)))
            .service(r("/productos/{id}/ml/precio").route(put().to(prod::set_precio_ml)))
            .service(r("/productos/{id}/historial").route(get().to(prod::historial)))
            .service(r("/config/ganancias").route(get().to(prod::get_config)).route(put().to(prod::set_config)))
            // Ventas centralizadas (órdenes de ML) + dashboard con ganancia real
            .service(r("/ventas/sincronizar").route(post().to(ventas::sincronizar)))
            .service(r("/ventas/dashboard").route(get().to(ventas::dashboard)))
            .service(r("/ventas/export").route(get().to(ventas::exportar)))
            .service(r("/ventas/envios").route(get().to(ventas::envios)))
            .service(r("/ventas/etiquetas").route(get().to(ventas::etiquetas)))
            .service(r("/ventas/{id}/etiqueta").route(get().to(ventas::etiqueta)))
            .service(r("/ventas").route(get().to(ventas::listar)))
            // SaaS: plan/suscripción + notificaciones
            .service(r("/mi-plan").route(get().to(saas::mi_plan)))
            .service(r("/notificaciones").route(get().to(saas::notificaciones)))
            .service(r("/notificaciones/leer").route(post().to(saas::marcar_leidas)))
            // Suscripción de pago (Mercado Pago)
            .service(r("/suscripcion").route(get().to(subs::estado)))
            .service(r("/suscripcion/pagos").route(get().to(subs::pagos)))
            .service(r("/suscripcion/suscribir").route(post().to(subs::suscribir)))
            .service(r("/suscripcion/cancelar").route(post().to(subs::cancelar)))
            .service(r("/suscripcion/webhook").route(post().to(subs::webhook)))
            // Datos de facturación (dueño)
            .service(r("/facturacion").route(get().to(fact::obtener)).route(put().to(fact::guardar)))
            // Cupones de descuento
            .service(r("/cupon/validar").route(post().to(cupon::validar)))
            .service(r("/admin/cupones").route(get().to(cupon::listar)).route(post().to(cupon::crear)))
            .service(r("/admin/cupones/{id}").route(put().to(cupon::set_activo)).route(delete().to(cupon::eliminar)))
            // Súper-admin (solo el dueño de la plataforma)
            .service(r("/admin/vendedores").route(get().to(adm::vendedores)))
            .service(r("/admin/vendedores/{id}/plan").route(put().to(adm::set_plan)))
            .service(r("/admin/vendedores/{id}/estado").route(put().to(adm::set_estado)))
            .service(r("/admin/metricas").route(get().to(adm::metricas)))
            // Auditoría (actividad del equipo, dueño)
            .service(r("/auditoria").route(get().to(audit::listar)))
            // API keys (gestión por el vendedor autenticado)
            .service(r("/api-keys").route(get().to(keys::listar)).route(post().to(keys::crear)))
            .service(r("/api-keys/{id}").route(delete().to(keys::revocar)))
            // Público: lo consumen las plataformas externas con X-API-Key
            .service(r("/pub/productos").route(get().to(pubc::productos)))
            .service(r("/pub/ventas").route(post().to(pubc::reportar_venta)))
            .service(r("/pub/devoluciones").route(post().to(pubc::reportar_devolucion))),
    );
}
